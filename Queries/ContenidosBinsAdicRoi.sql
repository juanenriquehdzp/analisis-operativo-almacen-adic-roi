WITH ENVIOS_ROI AS (
SELECT
MI.MOVIMIENTO, MI.FOLIO, MI.FECHA, MI.ESTATUS, LTRIM(RTRIM(MI.ID_SUCURSAL1)) DESTINO, LTRIM(RTRIM(S.PLAZA)) PLAZA,
MID.ARTICULO,
A.MARCA, A.ESTILO, A.NOMBRE,
LTRIM(RTRIM(CASE
WHEN	F.nom_rubro	=	'ISHU'	THEN	'CALZADO'
WHEN	F.nom_rubro	LIKE('%ROPA%')	THEN	'ROPA'
WHEN	F.nom_rubro	=	'ISHU ACC'	THEN	'ACCESORIOS'
ELSE	F.NOM_RUBRO
END))	AGRUP_RUBRO,
F.NOM_DEPTO,
MID.CANTIDAD,

DATEPART(MONTH, MI.FECHA) MES
FROM
MOVTOSINVENT(NOLOCK) MI
LEFT JOIN MOVTOSINVENTDET(NOLOCK) MID
	ON	MI.movimiento	=	MID.movimiento

LEFT JOIN ARTICULOS(NOLOCK) A
	ON	MID.articulo	=	A.articulo

LEFT JOIN FAMILIAS_LEO(NOLOCK)	F
	ON	A.familia	=	F.familia

LEFT JOIN SUCURSALES(NOLOCK) S
	ON	CAST(MI.cve_sucursal1 AS VARCHAR(4))	=	CAST(S.clave AS VARCHAR(4))
	AND	S.id_empresa	=	'BHERMANOS'

WHERE
	MI.tipo=	'TRAENV'
	AND	MI.id_sucursal	=	'ADIC_ROI'
	AND MI.estatus	<>	'CANCELADO'
	AND MI.id_sucursal1	<>	'CEDIS LEON'
	AND A.marca	<>	'JAVAS'

)

SELECT
MOVIMIENTO,
SUM(CANTIDAD) TOTAL_ENVIO,
CASE
	WHEN	SUM(CANTIDAD)	BETWEEN	0	AND	3	THEN '1 A 3 ARTS'
	WHEN	SUM(CANTIDAD)	BETWEEN	4	AND	6	THEN '4 A 6 ARTS'
	WHEN	SUM(CANTIDAD)	BETWEEN	7	AND	11	THEN '7 A 11 ARTS'
	WHEN	SUM(CANTIDAD)	>=		12	THEN '12 O MÁS'
	END TIPO_CAJA


--CASE
--	WHEN	SUM(CANTIDAD)	BETWEEN	0	AND	3	THEN 'MUY_BAJO'
--	WHEN	SUM(CANTIDAD)	BETWEEN	4	AND	6	THEN 'BAJO'
--	WHEN	SUM(CANTIDAD)	BETWEEN	7	AND	11	THEN 'ACEPTABLE'
--	WHEN	SUM(CANTIDAD)	>=		12	THEN 'CAJA_NORM'
--	END TIPO_CAJA
FROM
ENVIOS_ROI

GROUP BY
MOVIMIENTO

