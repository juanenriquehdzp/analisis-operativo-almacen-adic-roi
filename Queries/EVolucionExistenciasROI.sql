DECLARE @FECHA_CORTE DATE = '2026-10-12';
DECLARE @FECHA_INICIO DATE = '2026-07-01';

;WITH SEMANAS AS
(
    SELECT @FECHA_INICIO AS FECHA_SEMANA

    UNION ALL

    SELECT DATEADD(DAY, 7, FECHA_SEMANA)
    FROM SEMANAS
    WHERE DATEADD(DAY, 7, FECHA_SEMANA) < @FECHA_CORTE
),

BASE AS
(
    SELECT
        ED.TIENDA,
        LTRIM(RTRIM(S.ID_SUCURSAL)) AS ALMACEN,

        LTRIM(RTRIM(
            CASE
                WHEN F.NOM_RUBRO = 'ISHU' THEN 'CALZADO'
                WHEN F.NOM_RUBRO = 'ISHU ACC' THEN 'ACCESORIOS'
                WHEN F.NOM_RUBRO LIKE '%ROPA%' THEN 'ROPA'
                ELSE F.NOM_RUBRO
            END
        )) AS AGRUP_RUBRO,

        ED.FECHA,
        ED.ENTRADA - ED.SALIDA AS MOVIMIENTO

    FROM EXISTENCIASDET ED

    LEFT JOIN ARTICULOS A
        ON ED.ARTICULO = A.ARTICULO

    LEFT JOIN FAMILIAS_LEO F
        ON A.FAMILIA = F.FAMILIA

    LEFT JOIN SUCURSALES S
        ON ED.TIENDA = S.CLAVE
        AND S.ID_EMPRESA = 'BHERMANOS'

    WHERE ED.TIENDA = '1046'
      AND ED.FECHA < @FECHA_CORTE
      AND A.MARCA <> 'JAVAS'
),

SALDO_INICIAL AS
(
    SELECT
        TIENDA,
        ALMACEN,
        AGRUP_RUBRO,
        SUM(MOVIMIENTO) AS SALDO_INICIAL
    FROM BASE
    WHERE FECHA < @FECHA_INICIO
    GROUP BY
        TIENDA,
        ALMACEN,
        AGRUP_RUBRO
),

MOVIMIENTOS_SEMANALES AS
(
    SELECT
        TIENDA,
        ALMACEN,
        AGRUP_RUBRO,

        DATEADD(
            DAY,
            (DATEDIFF(DAY, @FECHA_INICIO, FECHA) / 7) * 7,
            @FECHA_INICIO
        ) AS FECHA_SEMANA,

        SUM(MOVIMIENTO) AS MOVIMIENTO_SEMANA

    FROM BASE

    WHERE FECHA >= @FECHA_INICIO

    GROUP BY
        TIENDA,
        ALMACEN,
        AGRUP_RUBRO,
        DATEADD(
            DAY,
            (DATEDIFF(DAY, @FECHA_INICIO, FECHA) / 7) * 7,
            @FECHA_INICIO
        )
),

GRUPOS AS
(
    SELECT TIENDA, ALMACEN, AGRUP_RUBRO
    FROM SALDO_INICIAL

    UNION

    SELECT TIENDA, ALMACEN, AGRUP_RUBRO
    FROM MOVIMIENTOS_SEMANALES
),

CALENDARIO AS
(
    SELECT
        G.TIENDA,
        G.ALMACEN,
        G.AGRUP_RUBRO,
        S.FECHA_SEMANA
    FROM GRUPOS G
    CROSS JOIN SEMANAS S
),

RESULTADO AS
(
    SELECT
        C.TIENDA,
        C.ALMACEN,
        C.AGRUP_RUBRO,
        C.FECHA_SEMANA,

        ISNULL(SI.SALDO_INICIAL, 0) AS SALDO_INICIAL,
        ISNULL(MS.MOVIMIENTO_SEMANA, 0) AS MOVIMIENTO_SEMANA

    FROM CALENDARIO C

    LEFT JOIN SALDO_INICIAL SI
        ON C.TIENDA = SI.TIENDA
        AND (
            C.ALMACEN = SI.ALMACEN
            OR (C.ALMACEN IS NULL AND SI.ALMACEN IS NULL)
        )
        AND (
            C.AGRUP_RUBRO = SI.AGRUP_RUBRO
            OR (C.AGRUP_RUBRO IS NULL AND SI.AGRUP_RUBRO IS NULL)
        )

    LEFT JOIN MOVIMIENTOS_SEMANALES MS
        ON C.TIENDA = MS.TIENDA
        AND (
            C.ALMACEN = MS.ALMACEN
            OR (C.ALMACEN IS NULL AND MS.ALMACEN IS NULL)
        )
        AND (
            C.AGRUP_RUBRO = MS.AGRUP_RUBRO
            OR (C.AGRUP_RUBRO IS NULL AND MS.AGRUP_RUBRO IS NULL)
        )
        AND C.FECHA_SEMANA = MS.FECHA_SEMANA
)

SELECT
    TIENDA,
    ALMACEN,

    DATEDIFF(DAY, @FECHA_INICIO, FECHA_SEMANA) / 7 + 1
        AS SEMANA_OPERACION,

    FECHA_SEMANA AS INICIO_SEMANA,

    CASE
        WHEN DATEADD(DAY, 7, FECHA_SEMANA) > @FECHA_CORTE
            THEN DATEADD(DAY, -1, @FECHA_CORTE)
        ELSE DATEADD(DAY, 6, FECHA_SEMANA)
    END AS FECHA_CORTE,

    AGRUP_RUBRO,
    SALDO_INICIAL,
    MOVIMIENTO_SEMANA,

    SALDO_INICIAL
    + SUM(MOVIMIENTO_SEMANA) OVER
    (
        PARTITION BY TIENDA, ALMACEN, AGRUP_RUBRO
        ORDER BY FECHA_SEMANA
        ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
    ) AS EXISTENCIA

FROM RESULTADO

ORDER BY
    TIENDA,
    AGRUP_RUBRO,
    FECHA_SEMANA

OPTION (MAXRECURSION 0);