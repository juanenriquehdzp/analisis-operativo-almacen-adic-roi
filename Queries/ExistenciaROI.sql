WITH 
COSTOS_APLI AS (
	SELECT
	C.ARTICULO,
	CASE
	WHEN	C.moneda=	'DL'
	THEN	(C.costoactual*20*1.16*C.FACTOR)
	ELSE	(C.costoactual*1.16*C.FACTOR)
	END	COSTO_IVA
	FROM
	COSTOS(NOLOCK) C
	INNER	JOIN ARTICULOS(NOLOCK) A
		ON	C.articulo	=	A.articulo
	WHERE
	C.grupo=	'01'
	AND A.tipoart<>'PIVOTE'

)
, EXISTENCIA_ROI AS (
SELECT
ED.TIENDA,
ED.ARTICULO,
A.MARCA, A.ESTILO, A.NOMBRE,
LTRIM(RTRIM(CASE
WHEN	F.nom_rubro	=	'ISHU'	THEN	'CALZADO'
WHEN	F.nom_rubro	=	'ISHU ACC'	THEN	'ACCESORIOS'
WHEN	F.nom_rubro	LIKE('%ROPA%')	THEN	'ROPA'
ELSE	F.NOM_RUBRO
END)) AgrupRubro,
LTRIM(RTRIM(F.NOM_DEPTO)) DEPTO,
SUM(ED.ENTRADA-ED.SALIDA) EXISTENCIA
FROM
EXISTENCIASDET(NOLOCK) ED
LEFT JOIN ARTICULOS(NOLOCK) A
	ON	ED.ARTICULO		=	A.ARTICULO
LEFT JOIN FAMILIAS_LEO(NOLOCK) F
	ON	A.familia	=	F.FAMILIA

WHERE
tienda	=	'1046'
AND A.MARCA NOT IN('JAVAS','ETQ')

GROUP BY
ED.TIENDA,
ED.ARTICULO,
A.MARCA, A.ESTILO, A.NOMBRE,
LTRIM(RTRIM(CASE
WHEN	F.nom_rubro	=	'ISHU'	THEN	'CALZADO'
WHEN	F.nom_rubro	=	'ISHU ACC'	THEN	'ACCESORIOS'
WHEN	F.nom_rubro	LIKE('%ROPA%')	THEN	'ROPA'
ELSE	F.NOM_RUBRO
END)),
LTRIM(RTRIM(F.NOM_DEPTO))

HAVING
SUM(ED.ENTRADA-ED.SALIDA)<>0
)

SELECT
ROI.TIENDA, ROI.ARTICULO, 
ROI.MARCA, ROI.ESTILO, ROI.NOMBRE, ROI.AgrupRubro, ROI.DEPTO,
ROI.EXISTENCIA, CA.COSTO_IVA,
(ROI.EXISTENCIA*CA.COSTO_IVA) TOTAL_COSTO
FROM
EXISTENCIA_ROI	ROI
LEFT JOIN COSTOS_APLI	CA
	ON	ROI.articulo	=	CA.articulo

WHERE
EXISTENCIA<0


ORDER BY
AgrupRubro, MARCA, ESTILO, ARTICULO

